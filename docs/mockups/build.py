#!/usr/bin/env python3
"""Build the lazuli design-direction mockups.

1. Writes <direction>/tokens.css from <direction>/tokens.json (tokens.json is the only source of values).
2. Serves this folder on 127.0.0.1 and screenshots every screen in both themes with headless Google Chrome
   at 1440x900, device scale 1: <direction>/<screen>-<theme>.png.

Usage: python3 docs/mockups/build.py [--css-only] [direction ...]
Standard library only. Chrome: /Applications/Google Chrome.app (override with CHROME=/path/to/binary).
"""
import functools
import http.server
import json
import os
import shutil
import subprocess
import sys
import threading
from pathlib import Path

HERE = Path(__file__).resolve().parent
DIRECTIONS = ["a-lapis", "b-cobalt", "c-denim"]
SCREENS = ["home", "file"]
THEMES = ["dark", "light"]
CHROME = os.environ.get("CHROME", "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome")


def fallback(role):
    return '"Apple SD Gothic Neo", sans-serif' if role == "ui" else '"Apple SD Gothic Neo", monospace'


def write_css(direction):
    doc = json.loads((HERE / direction / "tokens.json").read_text())
    ui, mono = doc["fonts"]["ui"]["family"], doc["fonts"]["mono"]["family"]
    lines = [f"/* Generated by ../build.py from tokens.json. Do not edit. */", ":root {"]
    lines.append(f'  --font-ui: "{ui}", {fallback("ui")};')
    lines.append(f'  --font-mono: "{mono}", "D2Coding", {fallback("mono")};')
    typo = doc["typography"]
    for step in ["xs", "sm", "md", "lg", "xl", "mono_md"]:
        t = typo[step]
        key = step.replace("_", "-")
        lines.append(f"  --t-{key}: {t['size']}px; --lh-{key}: {t['line_height']}px; --w-{key}: {t['weight']};")
    for k, v in doc["spacing"].items():
        lines.append(f"  --sp-{k}: {v}px;")
    for k, v in doc["radius"].items():
        lines.append(f"  --r-{k}: {v}px;")
    lines.append(f"  --icon-stroke: {doc['layout']['icon_stroke']};")
    lines.append("}")
    for theme in THEMES:
        lines.append(f':root[data-theme="{theme}"] {{')
        lines.append(f"  color-scheme: {theme};")
        for k, v in doc["color"][theme].items():
            lines.append(f"  --{k.replace('_', '-')}: {v};")
        lines.append("}")
    (HERE / direction / "tokens.css").write_text("\n".join(lines) + "\n")


class Quiet(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *args):
        pass


def shoot(directions):
    handler = functools.partial(Quiet, directory=str(HERE))
    server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), handler)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    port = server.server_address[1]
    profile = HERE / ".chrome-profile"  # removed again below; keeps every write inside this folder
    try:
        for d in directions:
            for screen in SCREENS:
                for theme in THEMES:
                    out = HERE / d / f"{screen}-{theme}.png"
                    url = f"http://127.0.0.1:{port}/{d}/{screen}.html?theme={theme}"
                    subprocess.run(
                        [CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--no-first-run",
                         "--force-device-scale-factor=1", "--window-size=1440,900", "--virtual-time-budget=4000",
                         f"--user-data-dir={profile}", f"--screenshot={out}", url],
                        check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=120)
                    print(out.relative_to(HERE))
    finally:
        server.shutdown()
        shutil.rmtree(profile, ignore_errors=True)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    directions = args or DIRECTIONS
    for d in directions:
        write_css(d)
    if "--css-only" not in sys.argv:
        shoot(directions)


if __name__ == "__main__":
    main()
